export type Locale = 'en' | 'my' | 'zh' | 'th' | 'ja' | 'ko';
export type Currency = 'USD' | 'MMK' | 'EUR' | 'THB' | 'CNY' | 'SGD' | 'JPY' | 'KRW';

/** Approximate display rates — for UI only, not live rates */
export const EXCHANGE_RATES: Record<Currency, number> = {
  USD: 1,
  MMK: 4200,
  EUR: 0.92,
  THB: 35,
  CNY: 7.25,
  SGD: 1.35,
  JPY: 155,
  KRW: 1350,
};

const CURRENCY_SYMBOLS: Record<Currency, string> = {
  USD: '$',
  MMK: 'K ',
  EUR: '€',
  THB: '฿',
  CNY: '¥',
  SGD: 'S$',
  JPY: '¥',
  KRW: '₩',
};

export function formatPrice(usdAmount: number, currency: Currency): string {
  const rate = EXCHANGE_RATES[currency];
  const symbol = CURRENCY_SYMBOLS[currency];
  const amount = usdAmount * rate;

  if (currency === 'MMK') {
    const mmk = Math.round(amount / 100) * 100;
    return `K ${mmk.toLocaleString()}`;
  }
  if (currency === 'JPY' || currency === 'KRW') {
    return `${symbol}${Math.round(amount).toLocaleString()}`;
  }
  return `${symbol}${amount.toFixed(2)}`;
}

